package dachser.backend.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Customer that pays for one or more shipments.
 * <p>
 * This is business data only: customers are not users of the application
 * (the application is used by the Finance Department).
 * Mapped to the {@code customers} table.
 */
@Entity
@Table(name = "customers")
@Getter
@Setter
@NoArgsConstructor
public class Customer {

    /** Technical identifier, generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Legal name of the customer. */
    @Column(name = "name", nullable = false, length = 150)
    private String name;

    /** Tax identification number; unique business key of the customer. */
    @Column(name = "tax_number", nullable = false, unique = true, length = 20)
    private String taxNumber;

    /** Contact e-mail (optional). */
    @Column(name = "email", length = 150)
    private String email;
}
