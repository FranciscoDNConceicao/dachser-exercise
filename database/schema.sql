-- =========================================================
-- Profit Calculation - schema
-- =========================================================

-- Customer that pays for the shipment (not an application user)
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    tax_number VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(150)
);

CREATE TABLE shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    shipment_code VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_shipment_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
);

CREATE TABLE incomes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,

    CONSTRAINT fk_income_shipment
        FOREIGN KEY (shipment_id)
        REFERENCES shipments(id),

    CONSTRAINT chk_income_amount
        CHECK (amount >= 0)
);

CREATE TABLE costs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,

    CONSTRAINT fk_cost_shipment
        FOREIGN KEY (shipment_id)
        REFERENCES shipments(id),

    CONSTRAINT chk_cost_amount
        CHECK (amount >= 0)
);

-- Historical snapshot of each calculation (use case post-condition)
CREATE TABLE profit_calculations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL,
    total_income DECIMAL(12, 2) NOT NULL,
    total_costs DECIMAL(12, 2) NOT NULL,
    profit_or_loss DECIMAL(12, 2) NOT NULL,
    calculated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_calculation_shipment
        FOREIGN KEY (shipment_id)
        REFERENCES shipments(id),

    -- Guarantees the stored result is always consistent
    CONSTRAINT chk_profit_or_loss
        CHECK (profit_or_loss = total_income - total_costs)
);

CREATE INDEX idx_shipments_customer_id
    ON shipments(customer_id);

CREATE INDEX idx_incomes_shipment_id
    ON incomes(shipment_id);

CREATE INDEX idx_costs_shipment_id
    ON costs(shipment_id);

-- Supports the calculation history query (by shipment, ordered by date)
CREATE INDEX idx_calculations_shipment_date
    ON profit_calculations(shipment_id, calculated_at);
